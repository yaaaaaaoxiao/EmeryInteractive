// Crystal structures described as data. Positions are fractional (units of the lattice parameter a).
// Everything else (all atom/site positions, neighbour counts, sites per cell, r/R) is generated in lattice.ts.

export type Vec3 = [number, number, number];

export type StructureId = 'fcc' | 'bcc' | 'sc';
export type SiteId = 'oct' | 'tet' | 'tri' | 'cubic' | 'square';

export interface SiteType {
  id: SiteId;
  name: string;
  color: number;
  // number of surrounding atoms (the BCC octahedron is distorted: 2 close + 4 farther atoms)
  coordination: number;
  // any one position of this site; the rest are generated by cubic symmetry + lattice centering
  representative: Vec3;
}

export interface Structure {
  id: StructureId;
  name: string;
  shortName: string;
  color: number;
  // atom radius R in units of a
  atomRadius: number;
  // lattice centering translations (atoms sit at these positions)
  centering: Vec3[];
  sites: SiteType[];
  // text for the info panel (KaTeX)
  info: {
    positions: string;
    touchAlong: string;
    touchEquation: string;
    atomsPerCell: string;
    latticeParameter: string;
    apf: string;
  };
}

